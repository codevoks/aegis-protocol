//! Multi-market, multi-actor world for the Phase 10 stateful invariant fuzzer
//! (`docs/phases/phase-10-security.md`, `docs/testing-strategy.md` §5).
//!
//! Two markets exist in every run, exercised in the SAME LiteSVM instance so cross-market
//! isolation (INV-RES-03, `A-PAR-02`) is genuinely tested under interleaved random operations, not
//! merely asserted once at setup:
//! - **Market 0** — classic SPL/SPL, SOL(9dp)/USDC(6dp) reference parameters
//!   (`reference_market_args`), identical to every earlier phase's fixture.
//! - **Market 1** — Token-2022 transfer-fee collateral / classic SPL loan, so the fuzzer's custody
//!   invariants (INV-CUS-01/02) are meaningfully exercised on a fee-bearing path (T-14), not just
//!   the fee-free path every other market in this repository already covers.
//!
//! Six actors (`docs/phases/phase-10-security.md` #15): two lenders, two borrowers, one
//! liquidator, one "attacker". The attacker participates in every ordinary permissionless action
//! exactly like the other five (a deliberate test of the design's own claim that no role gets
//! special treatment) and is also the reserved actor for `Action::DirectDonation` -- implemented
//! and callable, but not generated by the main random loop; see `actions::generate_step`'s doc
//! comment for exactly why mixing an INV-CUS-08 donation into the [GLOBAL]-invariant-checked
//! stream would make every later step a false positive rather than a real finding.

